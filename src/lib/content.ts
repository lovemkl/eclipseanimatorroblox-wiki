import fs from "fs";
import path from "path";
import { CONTENT_TYPES as CONFIG_CONTENT_TYPES } from "@/config/navigation";
import { routing, type Locale } from "@/i18n/routing";

// 从统一配置导入内容类型
export const CONTENT_TYPES = CONFIG_CONTENT_TYPES;

// 侧栏展示用短标题：剥品牌名前缀（导航只放关键词，压主词密度至 1-3%）
let NAV_BRAND = "";
try {
  NAV_BRAND = JSON.parse(fs.readFileSync(path.join(process.cwd(), "public/manifest.json"), "utf-8")).short_name || "";
} catch {
  // manifest 缺失时回退完整标题
}
function navLabel(fullTitle: string): string {
  if (NAV_BRAND && fullTitle.toLowerCase().startsWith(NAV_BRAND.toLowerCase())) {
    const stripped = fullTitle.slice(NAV_BRAND.length).replace(/^[\s:\-–—|]+/, "").trim();
    if (stripped) return stripped;
  }
  return fullTitle;
}


/**
 * 将文件名转换为 URL-safe slug
 * 所有非字母数字连字符下划线的字符（冒号、问号、井号、空格等）替换为 -
 * 合并连续的 -，去掉首尾 -
 */
export function fileNameToSlug(fileName: string): string {
  return fileName
    .replace(/\.mdx$/, "")
    .replace(/[^a-zA-Z0-9\-_]/g, "-")
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "");
}

/**
 * 根据 slug 在目录中反查真实文件名（不含 .mdx）
 * 例如 slug="gelum-boss" → 返回 "gelum:boss"
 */
export function findFileBySlug(dir: string, slug: string, basePath: string[] = []): string | null {
  if (!fs.existsSync(dir)) return null;
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      const result = findFileBySlug(fullPath, slug, [...basePath, entry.name]);
      if (result) return result;
    } else if (entry.name.endsWith(".mdx")) {
      const fileName = entry.name.replace(".mdx", "");
      const entrySlug = [...basePath, fileNameToSlug(fileName)].join("/");
      if (entrySlug === slug) {
        return [...basePath, fileName].join("/");
      }
    }
  }
  return null;
}

// 通用 Metadata 接口（与 MDX 文件 export const metadata 对应）
export interface ContentMetadata {
  title: string;
  description: string;
  category: string;
  date: string;
  lastModified?: string;
  image?: string;
  badge?: string;
  summary?: string;
}

// Heading 结构（从 MDX 源文件提取）
export interface Heading {
  id: string;
  text: string;
  level: number;
}

// 内容项接口
export interface ContentItem {
  slug: string;
  segments: string[];
  contentType: string;
  locale: Locale;
  metadata: ContentMetadata;
}

// 内容数据接口（含 MDX 组件）
export type ContentData = {
  slug: string;
  segments: string[];
  contentType: string;
  locale: Locale;
  metadata: ContentMetadata;
  MDXContent: React.ComponentType;
  headings: Heading[];
};

const CONTENT_ROOT = path.join(process.cwd(), "content");

// Build-time content index (generated by scripts/gen-content-manifest.mjs).
// Cloudflare Workers have no filesystem, so every directory scan below reads
// this manifest instead of content/ — article bodies still load via webpack's
// dynamic-import context, which works at runtime because manifest slugs match
// the MDX file names exactly.
import contentManifest from "../content-manifest.json";

type ManifestItem = {
  contentType: string;
  slug: string;
  title: string;
  badge?: string;
  date?: string;
  category?: string;
  headings: Heading[];
};

const manifestItems = (contentManifest as { items: ManifestItem[] }).items;

/**
 * 从 MDX 源文件中提取 ## 和 ### 标题
 */
function extractHeadings(mdxSource: string): Heading[] {
  const headings: Heading[] = [];
  const lines = mdxSource.split("\n");
  for (const line of lines) {
    const match = line.match(/^(#{2,3})\s+(.+)/);
    if (match) {
      const level = match[1].length;
      const text = match[2].replace(/\{[^}]*\}/g, "").trim();
      const id = text
        .toLowerCase()
        .replace(/[^a-z0-9\s-]/g, "")
        .replace(/\s+/g, "-")
        .replace(/-+/g, "-")
        .replace(/^-|-$/g, "");
      headings.push({ id, text, level });
    }
  }
  return headings;
}

/**
 * 读取 MDX 源文件并提取 headings
 */
function getHeadingsFromFile(filePath: string): Heading[] {
  try {
    const source = fs.readFileSync(filePath, "utf-8");
    return extractHeadings(source);
  } catch {
    return [];
  }
}

/**
 * 辅助函数：递归获取目录下所有 MDX 文件的 slug 路径
 */
function getSlugsFromDirectory(dir: string, basePath: string[] = []): string[][] {
  if (!fs.existsSync(dir)) return [];
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  const paths: string[][] = [];

  for (const entry of entries) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      paths.push(...getSlugsFromDirectory(fullPath, [...basePath, entry.name]));
    } else if (entry.name.endsWith(".mdx")) {
      const fileName = entry.name.replace(".mdx", "");
      paths.push([...basePath, fileNameToSlug(fileName)]);
    }
  }
  return paths;
}

/**
 * 获取所有内容列表（支持递归读取嵌套目录）
 * 使用动态 import 获取 MDX 文件的 metadata
 */
export async function getAllContent(contentType: string, language: Locale): Promise<ContentItem[]> {
  // manifest 只覆盖默认语言（en）；其他语言回退英文，避免非英语列表页为空
  const readLocale: Locale = routing.defaultLocale;
  const entries = manifestItems.filter((item) => item.contentType === contentType);

  const items = await Promise.all(
    entries.map(async (entry) => {
      const segments = entry.slug.split("/");
      const slug = entry.slug;
      try {
        const mod = await import(`../../content/${readLocale}/${contentType}/${slug}.mdx`);
        return {
          slug,
          segments,
          contentType,
          locale: readLocale,
          metadata: mod.metadata as ContentMetadata,
        } satisfies ContentItem;
      } catch {
        return null;
      }
    }),
  );

  return items
    .filter((item): item is ContentItem => Boolean(item))
    .sort((a, b) => a.metadata.title.localeCompare(b.metadata.title));
}

/**
 * 获取单个内容项（含 MDX 渲染后的内容组件）
 * 使用动态 import 直接导入 .mdx 文件
 */
export async function getContent(contentType: string, slugSegments: string[], language: Locale): Promise<ContentData | null> {
  const currentSlug = slugSegments.join("/");
  const manifestEntry = manifestItems.find(
    (item) => item.contentType === contentType && item.slug === currentSlug
  );

  try {
    const { default: MDXContent, metadata } = await import(
      `../../content/${routing.defaultLocale}/${contentType}/${currentSlug}.mdx`
    );

    return {
      slug: currentSlug,
      segments: slugSegments,
      contentType,
      locale: routing.defaultLocale,
      metadata: metadata as ContentMetadata,
      MDXContent,
      headings: manifestEntry?.headings ?? getHeadingsFromFile(path.join(CONTENT_ROOT, routing.defaultLocale, contentType, `${currentSlug}.mdx`)),
    };
  } catch {
    // manifest 未命中且直连 import 失败（例如 es/pt/de 请求）——slug 相同，正文回退英文
    if (language !== routing.defaultLocale) {
      try {
        const enContentDir = path.join(CONTENT_ROOT, routing.defaultLocale, contentType);
        const enRealSlug = findFileBySlug(enContentDir, currentSlug) || currentSlug;
        const enMdxPath = path.join(enContentDir, `${enRealSlug}.mdx`);
        const { default: MDXContent, metadata } = await import(
          `../../content/${routing.defaultLocale}/${contentType}/${enRealSlug}.mdx`
        );
        return {
          slug: currentSlug,
          segments: slugSegments,
          contentType,
          locale: routing.defaultLocale,
          metadata: metadata as ContentMetadata,
          MDXContent,
          headings: manifestEntry?.headings ?? getHeadingsFromFile(enMdxPath),
        };
      } catch {
        return null;
      }
    }
    return null;
  }
}

/**
 * 导航分组结构（用于动态 Wiki Navigation）
 */
export interface NavGroup {
  /** 分组标题，来自目录名转人类可读格式，如 "bosses" → "Bosses" */
  title: string;
  /** 该分组下的文章数量 */
  count: number;
  /** 分组 slug（即目录名，如 "bosses"） */
  slug: string;
  /** 文章链接列表 */
  links: Array<{ label: string; href: string; badge?: string }>;
}

// 分组标题映射：slug → 人类可读标题（默认英文）
const GROUP_TITLES: Record<string, string> = {
  guide: "Guides",
  beasts: "Beasts",
  arenas: "Arenas",
  tips: "Tips & Tactics",
};

// 西语分组标题映射
const GROUP_TITLES_ES: Record<string, string> = {
  guide: "Guías", beasts: "Bestias", arenas: "Arenas", tips: "Consejos y tácticas",
};
const GROUP_TITLES_PT: Record<string, string> = {
  guide: "Guias", beasts: "Feras", arenas: "Arenas", tips: "Dicas e táticas",
};
const GROUP_TITLES_DE: Record<string, string> = {
  guide: "Guides", beasts: "Bestien", arenas: "Arenen", tips: "Tipps & Taktik",
};

// locale → 分组标题映射
const GROUP_TITLES_BY_LOCALE: Record<string, Record<string, string>> = {
  es: GROUP_TITLES_ES, pt: GROUP_TITLES_PT, de: GROUP_TITLES_DE,
};

// locale → "Overview" 翻译
const OVERVIEW_LABEL_BY_LOCALE: Record<string, string> = {
  es: "Resumen", pt: "Visão geral", de: "Übersicht",
};

// 分组排序顺序
const GROUP_ORDER: string[] = [
  "guide", "weapons", "gangs", "codes",
];

/**
 * 动态生成 Wiki Navigation 分组
 * 扫描 content/<locale>/ 下的所有 MDX 文件，按子目录分组
 * 同时为列表页添加 Overview 入口
 */
export function getDynamicNavigation(language: Locale = "en"): NavGroup[] {
  const groups: NavGroup[] = [];
  const contentTypeSet = new Set<string>(CONTENT_TYPES);

  // manifest 按 contentType 分组（跳过不在 CONTENT_TYPES 中的目录，避免显示会 404 的导航链接）
  const byType = new Map<string, ManifestItem[]>();
  for (const item of manifestItems) {
    if (!contentTypeSet.has(item.contentType as typeof CONTENT_TYPES[number])) continue;
    const list = byType.get(item.contentType) ?? [];
    list.push(item);
    byType.set(item.contentType, list);
  }

  for (const [groupSlug, items] of byType) {
    if (items.length === 0) continue;

    const links: NavGroup["links"] = [];
    // 添加 Overview 入口（按 locale 翻译）
    const overviewLabel = OVERVIEW_LABEL_BY_LOCALE[language] || "Overview";
    links.push({ label: overviewLabel, href: `/${groupSlug}` });

    for (const item of items) {
      const articleSlug = item.slug;
      links.push({ label: navLabel(item.title), href: `/${groupSlug}/${articleSlug}`, badge: item.badge });
    }

    // 优先使用 locale 特定标题，否则回退到英文默认
    const localTitles = GROUP_TITLES_BY_LOCALE[language] || {};
    const groupTitle = localTitles[groupSlug] || GROUP_TITLES[groupSlug] || groupSlug.replace(/-/g, " ").replace(/\b\w/g, (c) => c.toUpperCase());

    groups.push({
      title: groupTitle,
      count: links.length - 1, // 减去 Overview
      slug: groupSlug,
      links,
    });
  }

  // 按 GROUP_ORDER 排序
  groups.sort((a, b) => {
    const ai = GROUP_ORDER.indexOf(a.slug);
    const bi = GROUP_ORDER.indexOf(b.slug);
    return (ai === -1 ? 999 : ai) - (bi === -1 ? 999 : bi);
  });

  return groups;
}

/**
 * 获取所有内容路径（用于 generateStaticParams）
 */
export async function getAllContentPaths(language: Locale) {
  if (language !== routing.defaultLocale) {
    // 非英语语言没有内容目录，回退英文（与 getAllContent 的回退一致）
    language = routing.defaultLocale;
  }
  return manifestItems
    .filter((item) => item.contentType)
    .map((item) => ({
      contentType: item.contentType,
      slug: item.slug.split("/"),
    }));
}
